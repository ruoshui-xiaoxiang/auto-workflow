def build(lines):
    spk = list(SPEAKERS); gi = 0
    for s in SHOTS:
        i, j = s['lines']
        s['text'] = '\n'.join(lines[i:j + 1])
        s['dlg'] = []
        for m in re.finditer(r'“(.*?)”', s['text'], re.S):
            if gi >= len(spk):
                raise SystemExit('说话人表比台词短：多出一条 %r' % m.group(1))
            s['dlg'].append((spk[gi], m.group(1))); gi += 1
    if gi != len(spk):
        raise SystemExit('台词条数不符：正文抓到 %d 条，说话人表 %d 条' % (gi, len(spk)))
    for s in SHOTS:
        hd, tl = BOUND[s['id']]
        if not s['text'].startswith(hd):
            raise SystemExit('%s 切片开头漂了：应「%s…」实「%s…」' % (s['id'], hd, s['text'][:18]))
        if not s['text'].rstrip().endswith(tl):
            raise SystemExit('%s 切片结尾漂了：应「…%s」实「…%s」' % (s['id'], tl, s['text'].rstrip()[-16:]))
    prev_end = -1
    for s in SHOTS:
        i, j = s['lines']
        if i != prev_end + 1:
            raise SystemExit('%s 切片不接：%d 行起，上一镜止于 %d 行' % (s['id'], i, prev_end))
        prev_end = j
    print('逐字覆盖：第一章 %d 行 = %d 镜切片首尾相接，台词 %d 条全部配到说话人'
          % (len(lines), len(SHOTS), gi))
    return prev_end + 1 == len(lines) or lines[-1].strip() == ''

# ---------------------------------------------------------------- 时长与帧数
def timing(s):
    ch = sum(len(t) for _, t in s['dlg'])
    dlg = ch / CPS + max(0, len(s['dlg']) - 1) * GAP
    dur = round(max(s['act'], dlg), 2)
    need = int(dur * FPS)
    n = 7
    while GRID(n) < need: n += 1
    fr = min(GRID(n), MAXF)
    s['ch'], s['dlg_s'], s['dur'], s['frames'] = ch, round(dlg, 2), dur, fr
    s['secs'] = round(fr / FPS, 2)
    s['over'] = need > MAXF
    return s

